// Usage: node tools/build-data.mjs [path/to/workbook.xlsx]
// Without an argument it uses the newest .xlsx in /data. Rewrites public/data.js.
import { createRequire } from 'module';
import { writeFileSync, readFileSync, readdirSync, statSync } from 'fs';
import path from 'path';
const require = createRequire(import.meta.url);
const XLSX = require('xlsx');
const core = require('../public/core.js');
let file = process.argv[2];
if (!file) {
  const dir = new URL('../data/', import.meta.url).pathname;
  const xs = readdirSync(dir).filter(f => /\.xlsx$/i.test(f) && !f.startsWith('~$')).map(f => path.join(dir, f));
  if (!xs.length) { console.error('No .xlsx found in /data'); process.exit(1); }
  file = xs.sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs)[0];
}
const buf = readFileSync(file);
const names = XLSX.read(buf, { bookSheets: true }).SheetNames;
const sN = names.find(n => /^sale\s*register$/i.test(n.trim())) || names.find(n => /sale/i.test(n));
const tN = names.find(n => /^target$/i.test(n.trim())) || names.find(n => /target/i.test(n) && !/achiev/i.test(n));
if (!sN || !tN) { console.error('Sheets "Sale Register" and "Target" not found. Found: ' + names.join(', ')); process.exit(1); }
const wb = XLSX.read(buf, { sheets: [sN, tN], cellFormula: false, cellStyles: false });
const mx = n => XLSX.utils.sheet_to_json(wb.Sheets[n], { header: 1, raw: true, defval: null });
const sr = core.matrixToRows(mx(sN), core.SALES_MUST);
const tg = core.matrixToRows(mx(tN), core.TARGET_MUST);
if (!sr || !tg) { console.error('Required headers missing in one of the sheets.'); process.exit(1); }
const ds = core.buildDataset(sr, tg);
if (!ds.counts.sales) { console.error('No usable sale rows found.'); process.exit(1); }
writeFileSync(new URL('../public/data.js', import.meta.url),
  '/* Built-in data, generated by tools/build-data.mjs from /data/*.xlsx. Do not edit by hand. */\nconst EMBED=' + JSON.stringify(ds) +
  ';\nconst EMBED_META={name:' + JSON.stringify(path.basename(file)) + ',custom:false};\n');
console.log(path.basename(file) + ': ' + ds.counts.sales + ' sale rows, ' + ds.counts.target + ' target rows -> public/data.js');
